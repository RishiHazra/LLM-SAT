def query_gpt(preferences: str) -> Tuple[str, int, int]:
    """
    :param preferences: food preferences of people
    :return: raw output generated by gpt-* model, # prompt_tokens, # completion_tokens
    """
    response = openai.ChatCompletion.create(
        model="gpt-4-1106-preview",
        messages=[
            {"role": "system", "content": "Your task is to output two distinct lists of food items, one denoting what "
                                          "can be ordered ('orderable') and the other what cannot ('not_orderable'), "
                                          "to meet the preferences of a group of individuals. Each person must find "
                                          "the selection satisfactory based on their likes and dislikes. The "
                                          "satisfaction criteria are: 1. A person is satisfied if at least one liked "
                                          "item is in 'orderable' list or one disliked item is in 'not_orderable' list. "
                                          "2. No item can appear on both lists. 3. All participants must be satisfied "
                                          "by the combination of the two lists. 4. If no such combination exists that "
                                          "satisfies all, output empty lists for both. You always think step-by-step "
                                          "and show all your work in the explanation. "
                                          "Output your final solution as comma separated list of strings in python code "
                                          "<orderable=[...], not_orderable=[...]>."
             },
            {"role": "user", "content": f"{preferences}"},
        ],
        temperature=1,
        max_tokens=4096,
        top_p=1,
        frequency_penalty=0,
        presence_penalty=0
    )

    return (response['choices'][0]['message']['content'],
            response['usage']['prompt_tokens'],
            response['usage']['completion_tokens'])


if __name__ == "__main__":
    scores = 0
    data_path = os.path.join(os.environ["ROOT_PATH"], 'dataset.pkl')
    sat_dataset = SatDataset(root_path=os.environ["ROOT_PATH"], data_path=data_path)
    sat_loader = DataLoader(sat_dataset, batch_size=1, shuffle=True, collate_fn=custom_collate)

    for data_sample in tqdm(sat_loader):
        data_sample = DotMap(data_sample[0])
        while True:
            try:
                gpt_out, num_prompt_tokens, num_completion_tokens = query_gpt(data_sample.preferences)
                log_data_sample(data_sample.num_vars, data_sample.num_clauses,
                                data_sample.formula, data_sample.is_sat,
                                data_sample.preferences, data_sample.menu_items,
                                gpt_out, num_prompt_tokens, num_completion_tokens)
                break
            except openai.error.RateLimitError:
                time.sleep(10)


    net_score = scores / len(sat_dataset)
    print(f"Net Score: {net_score}")


